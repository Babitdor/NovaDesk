//! The request file a harness may write during a turn.
//!
//! Nova Desktop has no channel an agent can call, and inventing a CLI feature for
//! one would couple the app to a specific harness. The contract is a file instead:
//!
//! ```text
//! NOVA_DESKTOP_REQUESTS=<app data>/requests/<task or personality>.jsonl
//! ```
//!
//! The variable is set on the harness process, the file is cleared before a turn
//! and read *after* it, emitting one event per line. A harness that never writes
//! the file changes nothing, which is why today's nova pipeline is unaffected.
//! One JSON object per line, at most twenty lines and 64 KiB; anything else is
//! ignored rather than guessed at.

use std::path::{Path, PathBuf};

use serde::Deserialize;

pub const ENV: &str = "NOVA_DESKTOP_REQUESTS";
pub const MAX_BYTES: u64 = 64 * 1024;
pub const MAX_LINES: usize = 20;
const MAX_PROMPT: usize = 12_000;
const MAX_THREAD: usize = 200;
const MAX_AGENT: usize = 40;

#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(
    tag = "type",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum Request {
    /// Start a new task with this prompt.
    Wakeup {
        prompt: String,
        agent: Option<String>,
        after_seconds: Option<u64>,
    },
    /// Put a message in another task by id.
    ThreadMessage { thread: String, text: String },
}

/// Where one turn's requests file would live. The turn id is generated by the
/// command layer, never by a harness, so a path cannot be steered elsewhere.
pub fn path_for(dir: &Path, turn_id: &str) -> PathBuf {
    dir.join("requests").join(format!("{turn_id}.jsonl"))
}

/// Reads the file the harness left behind. Every failure mode — missing file, a
/// line that is not JSON, an unknown type, a field that is too long — is a
/// no-op, so this can run after every turn without a guard.
pub fn read(path: &Path) -> Vec<Request> {
    let Ok(meta) = std::fs::metadata(path) else {
        return Vec::new();
    };
    if !meta.is_file() || meta.len() > MAX_BYTES {
        return Vec::new();
    }
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    parse(&text)
}

pub fn parse(text: &str) -> Vec<Request> {
    text.lines()
        .filter(|line| !line.trim().is_empty())
        .take(MAX_LINES)
        .filter_map(|line| serde_json::from_str::<Request>(line).ok())
        .filter(valid)
        .collect()
}

fn valid(request: &Request) -> bool {
    match request {
        Request::Wakeup {
            prompt,
            agent,
            after_seconds,
        } => {
            let prompt = prompt.trim();
            !prompt.is_empty()
                && prompt.chars().count() <= MAX_PROMPT
                && agent.as_ref().map_or(true, |agent| {
                    !agent.is_empty() && agent.chars().count() <= MAX_AGENT
                })
                // A week is the outer bound: a longer wait is a schedule, and this
                // process will have exited long before it fires.
                && after_seconds.map_or(true, |seconds| seconds <= 7 * 24 * 60 * 60)
        }
        Request::ThreadMessage { thread, text } => {
            !thread.trim().is_empty()
                && thread.chars().count() <= MAX_THREAD
                && !text.trim().is_empty()
                && text.chars().count() <= MAX_PROMPT
        }
    }
}

/// Removes the file after it has been read: the next turn gets its own path, and
/// a stale request must not be replayed by a restart.
pub fn clear(path: &Path) {
    let _ = std::fs::remove_file(path);
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testtmp::TempDir;

    #[test]
    fn a_missing_file_is_no_requests() {
        let dir = TempDir::new("requests-missing");
        assert!(read(&path_for(dir.path(), "turn-1")).is_empty());
    }

    #[test]
    fn valid_lines_are_read_and_unknown_ones_are_skipped() {
        let dir = TempDir::new("requests-parse");
        let path = path_for(dir.path(), "turn-2");
        std::fs::create_dir_all(path.parent().expect("requests dir")).expect("create");
        std::fs::write(
            &path,
            concat!(
                "{\"type\":\"wakeup\",\"prompt\":\"run the tests\"}\n",
                "not json\n",
                "{\"type\":\"threadMessage\",\"thread\":\"abc\",\"text\":\"hello\"}\n",
                "{\"type\":\"unknown\",\"prompt\":\"x\"}\n",
                "{\"type\":\"wakeup\",\"prompt\":\"   \"}\n",
            ),
        )
        .expect("write requests");
        assert_eq!(
            read(&path),
            vec![
                Request::Wakeup {
                    prompt: "run the tests".into(),
                    agent: None,
                    after_seconds: None
                },
                Request::ThreadMessage {
                    thread: "abc".into(),
                    text: "hello".into()
                },
            ]
        );
    }

    #[test]
    fn only_the_first_twenty_lines_are_read() {
        let mut text = String::new();
        for index in 0..40 {
            text.push_str(&format!("{{\"type\":\"wakeup\",\"prompt\":\"{index}\"}}\n"));
        }
        assert_eq!(parse(&text).len(), MAX_LINES);
    }

    #[test]
    fn an_oversized_file_is_ignored_whole() {
        let dir = TempDir::new("requests-huge");
        let path = path_for(dir.path(), "turn-3");
        std::fs::create_dir_all(path.parent().expect("requests dir")).expect("create");
        let line = "{\"type\":\"wakeup\",\"prompt\":\"x\"}\n";
        let big = line.repeat(4000);
        std::fs::write(&path, big).expect("write requests");
        assert!(read(&path).is_empty());
    }

    #[test]
    fn clear_removes_the_file() {
        let dir = TempDir::new("requests-clear");
        let path = path_for(dir.path(), "turn-4");
        std::fs::create_dir_all(path.parent().expect("requests dir")).expect("create");
        std::fs::write(&path, "{\"type\":\"wakeup\",\"prompt\":\"x\"}\n").expect("write");
        clear(&path);
        assert!(!path.exists());
    }
}
